#!/usr/bin/env python3
"""
tools/gen_test_harness.py

Scans UEFI/TestHarness/cases/ for GPU_TEST declarations, then generates:
  1. UEFI/TestHarness/test_registry.h (Forward declarations & externs)
  2. UEFI/TestHarness/test_registry.c (Static dispatch table)
  3. Updates [Sources] section in UEFI/TestHarness/TestHarness.inf
"""

import argparse
import os
import re
import sys

RE_GPU_TEST = re.compile(
    r'GPU_TEST\s*\(\s*([A-Za-z0-9_]+)\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)',
    re.MULTILINE
)

def find_repo_root():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    return os.path.abspath(os.path.join(script_dir, ".."))

def scan_test_cases(cases_dir, base_dir):
    """
    Recursively scans cases_dir for .c files and extracts GPU_TEST macros.
    Returns:
      tests: list of dicts: {'func': str, 'path': str, 'desc': str, 'source': str}
      sources: set of relative paths to .c files containing tests
    """
    tests = []
    sources = set()

    if not os.path.isdir(cases_dir):
        print(f"[WARN] Cases directory does not exist: {cases_dir}")
        return tests, list(sources)

    for root, _, files in os.walk(cases_dir):
        for f in sorted(files):
            if f.endswith(".c"):
                abs_path = os.path.join(root, f)
                rel_path = os.path.relpath(abs_path, base_dir)
                
                with open(abs_path, "r", encoding="utf-8") as fp:
                    content = fp.read()

                matches = RE_GPU_TEST.findall(content)
                if matches:
                    sources.add(rel_path)
                    for func_name, test_path, test_desc in matches:
                        tests.append({
                            "func": func_name,
                            "path": test_path,
                            "desc": test_desc,
                            "source": rel_path
                        })

    # Sort deterministically by test path
    tests.sort(key=lambda t: t["path"])
    return tests, sorted(list(sources))

def generate_header(tests, output_path):
    lines = [
        "// ============================================================================",
        "// AUTOGENERATED FILE - DO NOT EDIT DIRECTLY",
        "// Generated by tools/gen_test_harness.py",
        "// ============================================================================",
        "",
        "#ifndef __TEST_REGISTRY_H__",
        "#define __TEST_REGISTRY_H__",
        "",
        '#include "harness.h"',
        "",
        "// Forward declarations of discovered test functions",
    ]

    for t in tests:
        lines.append(f"TEST_STATUS {t['func']}(IN GOP_3D_PROTOCOL *Gop3D);")

    lines.extend([
        "",
        "// Test registry export",
        "extern CONST GPU_TEST_NODE gTestRegistry[];",
        "extern CONST UINTN         gTestRegistryCount;",
        "",
        "#endif // __TEST_REGISTRY_H__",
        ""
    ])

    content = "\n".join(lines)
    with open(output_path, "w", encoding="utf-8") as fp:
        fp.write(content)
    print(f"[GEN] Emitted header: {output_path}")

def generate_source(tests, output_path):
    lines = [
        "// ============================================================================",
        "// AUTOGENERATED FILE - DO NOT EDIT DIRECTLY",
        "// Generated by tools/gen_test_harness.py",
        "// ============================================================================",
        "",
        '#include "harness.h"',
        '#include "test_registry.h"',
        "",
        "CONST GPU_TEST_NODE gTestRegistry[] = {"
    ]

    for t in tests:
        lines.extend([
            "    {",
            f'        "{t["path"]}",',
            f'        "{t["desc"]}",',
            f"        {t['func']}",
            "    },"
        ])

    lines.extend([
        "};",
        "",
        "CONST UINTN gTestRegistryCount = sizeof(gTestRegistry) / sizeof(gTestRegistry[0]);",
        ""
    ])

    content = "\n".join(lines)
    with open(output_path, "w", encoding="utf-8") as fp:
        fp.write(content)
    print(f"[GEN] Emitted table : {output_path}")

def update_inf_sources(inf_path, test_sources):
    """
    Updates the [Sources] section in TestHarness.inf to include app.c,
    test_registry.c, and all discovered test case .c files.
    """
    if not os.path.isfile(inf_path):
        print(f"[WARN] INF file not found: {inf_path}")
        return

    with open(inf_path, "r", encoding="utf-8") as fp:
        content = fp.read()

    # Base sources required by the harness
    all_sources = ["app.c", "test_registry.c"] + test_sources
    sources_block = "[Sources]\n" + "\n".join(f"  {s}" for s in all_sources) + "\n"

    # Replace existing [Sources] section
    pattern = re.compile(r'\[Sources\][^\[]*', re.MULTILINE)
    if pattern.search(content):
        new_content = pattern.sub(sources_block, content)
    else:
        # Prepend before [Packages] if missing
        new_content = content.replace("[Packages]", sources_block + "\n[Packages]")

    with open(inf_path, "w", encoding="utf-8") as fp:
        fp.write(new_content)
    print(f"[GEN] Updated INF   : {inf_path} ({len(all_sources)} source files)")

def main():
    parser = argparse.ArgumentParser(description="Generate GPUemu test harness registry.")
    parser.add_argument("--harness-dir", default=None, help="Path to UEFI/TestHarness directory")
    parser.add_argument("--dry-run", action="store_true", help="Print discovered tests without writing files")
    args = parser.parse_args()

    repo_root = find_repo_root()
    harness_dir = args.harness_dir or os.path.join(repo_root, "UEFI", "TestHarness")
    cases_dir = os.path.join(harness_dir, "cases")
    inf_path = os.path.join(harness_dir, "TestHarness.inf")
    header_path = os.path.join(harness_dir, "test_registry.h")
    source_path = os.path.join(harness_dir, "test_registry.c")

    print(f"[GEN] Scanning test cases in: {cases_dir}")
    tests, sources = scan_test_cases(cases_dir, harness_dir)

    print(f"[GEN] Discovered {len(tests)} tests across {len(sources)} files:")
    for t in tests:
        print(f"  - {t['path']} -> {t['func']}() ({t['source']})")

    if args.dry_run:
        print("[GEN] Dry run complete. No files written.")
        return 0

    generate_header(tests, header_path)
    generate_source(tests, source_path)
    update_inf_sources(inf_path, sources)
    print(f"[GEN] Test harness autogeneration completed successfully.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
